export function translateText(value: string, locale: Locale): string {
  if (locale === 'vi') return value;
  const text = value.replace(/\s+/g, ' ').trim();
  if (english[text]) return english[text];
  return text
    .replace(/^(?:Số phòng|Phòng): (\d+)$/, 'Rooms: $1')
    .replace(/^(?:Số tầng|Tầng): (\d+)$/, 'Floors: $1')
    .replace(/^Phòng\s+/, 'Room ')
    .replace(/ — Ảnh (\d+)$/, ' — Photo $1')
    .replace(/^Không gian November Homestay — Ảnh /, 'November Homestay — Photo ')
    .replace(/^Ảnh (\d+) trên (\d+)$/, 'Image $1 of $2')
    .replace(/^\/ Nội quy của home$/, '/ House rules')
    .replace(/^Diện tích: /, 'Area: ')
    .replace(/^Đến ([\d.]+)đ$/, 'Up to $1 VND')
    .replace(/^Khám phá (\d+) phòng ↓$/, 'Explore $1 rooms ↓')
    .replace(/^(\d+) căn phòng dành cho bạn$/, '$1 rooms for you')
    .replace(/^(\d+) căn phòng đã lưu$/, '$1 saved rooms')
    .replace(/^Xem (\d+) phòng ↗$/, 'View $1 rooms ↗')
    .replace(/^Xem (.+) tại (.+)$/, 'View $1 at $2')
    .replace(/^Chi tiết /, 'View ')
    .replace(/^Lưu /, 'Save ')
    .replace(/^Bỏ lưu /, 'Unsave ')
    .replace(/^← Khám phá phòng khác tại /, '← More rooms at ')
    .replace(/^10h-14h$/, '10 am–2 pm')
    .replace(/^16h-20h$/, '4 pm–8 pm')
    .replace(/^21h-9h \(ngày hôm sau\)$/, '9 pm–9 am (next day)')
    .replace(/^14h-12h \(ngày hôm sau\)$/, '2 pm–12 noon (next day)')
    .replace(/^(\d+) trên 5 sao$/, '$1 out of 5 stars')
    .replace(/^Xem ảnh (\d+)$/, 'View photo $1')
    .replace(/^Xem ảnh banner (\d+)$/, 'View banner image $1');
}
